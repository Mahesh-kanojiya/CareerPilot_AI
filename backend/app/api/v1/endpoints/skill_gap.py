from typing import List
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.api.deps import get_current_user
from app.models.user import User
from app.models.resume import Resume
from app.models.job import Job
from app.models.skill_gap import SkillGapReport
from app.schemas.skill_gap import SkillGapRequest, SkillGapResponse
from app.services.skill_gap_service import SkillGapService

router = APIRouter()

@router.post("/analyze", response_model=SkillGapResponse)
async def analyze_skill_gap(
    req: SkillGapRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """
    Diagnose skill gaps between candidate's active resume and a target job or role.
    Generates structured roadmap steps with timeframes, topics, and projects.
    """
    active_resume = db.query(Resume).filter(
        Resume.user_id == current_user.id,
        Resume.is_active == True
    ).first()

    if not active_resume:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Active resume required. Please upload your resume first."
        )

    job = None
    if req.job_id:
        job = db.query(Job).filter(Job.id == req.job_id).first()
        if not job:
            raise HTTPException(status_code=404, detail="Specified job posting not found.")

    report = await SkillGapService.analyze_gap(
        resume=active_resume,
        job=job,
        target_role=req.target_role
    )

    # Persist report for user dashboard
    db_report = SkillGapReport(
        user_id=current_user.id,
        job_id=job.id if job else None,
        target_role=report.target_role,
        match_score=report.match_score,
        matching_skills=report.matching_skills,
        missing_skills=report.missing_skills,
        roadmap_json=[s.model_dump() for s in report.roadmap]
    )
    db.add(db_report)
    db.commit()
    db.refresh(db_report)

    report.id = db_report.id
    return report

@router.get("/history", response_model=List[dict])
def get_skill_gap_history(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """List previous skill gap reports generated by the user."""
    reports = db.query(SkillGapReport).filter(
        SkillGapReport.user_id == current_user.id
    ).order_by(SkillGapReport.created_at.desc()).limit(10).all()

    return [
        {
            "id": r.id,
            "target_role": r.target_role,
            "job_id": r.job_id,
            "match_score": r.match_score,
            "matching_skills": r.matching_skills,
            "missing_skills": r.missing_skills,
            "created_at": r.created_at
        }
        for r in reports
    ]
